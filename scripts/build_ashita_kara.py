MAX_SUB_CHARS = 55  # 자막 한 큐 최대 글자 수(1920 폭·50px 기준 2줄 이내)


def split_sentences(text, enders):
    parts, cur = [], ""
    for ch in text:
        cur += ch
        if ch in enders:
            parts.append(cur.strip())
            cur = ""
    if cur.strip():
        parts.append(cur.strip())
    return parts


def pack(parts, limit):
    """문장들을 limit 글자 이내 묶음으로 합친다. (묶음 텍스트, 묶음 안 문장 수) 목록."""
    chunks, cur, cnt = [], "", 0
    for ptxt in parts:
        if cur and len(cur) + len(ptxt) > limit:
            chunks.append((cur, cnt))
            cur, cnt = ptxt, 1
        else:
            cur, cnt = (cur + ptxt) if cur else ptxt, cnt + 1
    if cur:
        chunks.append((cur, cnt))
    return chunks


def split_line(ln):
    """긴 내레이션 줄을 문장 경계에서 자막 큐(=TTS 줄) 여러 개로 나눈다. 한국어는 문장 수 비례로 따라 나눈다."""
    if ln.style != N or len(ln.ja) <= MAX_SUB_CHARS:
        return [ln]
    packed = pack(split_sentences(ln.ja, "。！？"), MAX_SUB_CHARS)
    if len(packed) == 1:
        return [ln]
    ja_chunks = [c for c, _ in packed]
    counts = [n for _, n in packed]
    ko_sents = split_sentences(ln.ko, ".!?")
    ko_chunks, pos = [], 0
    if len(ko_sents) == sum(counts):      # 문장 수가 같으면 같은 묶음으로
        for n in counts:
            ko_chunks.append(" ".join(ko_sents[pos:pos + n]))
            pos += n
    else:                                 # 다르면 쉼표 절 단위로, 일본어 묶음 글자 비율에 맞춰
        clauses = [c.strip() for c in re.split(r"(?<=,) ", ln.ko) if c.strip()]
        ja_total = sum(len(c) for c in ja_chunks)
        acc, ci = 0, 0
        for k, c in enumerate(ja_chunks):
            acc += len(c)
            target = len(ln.ko) * acc / ja_total
            taken = []
            while ci < len(clauses) and (k == len(ja_chunks) - 1 or
                                         sum(len(x) for x in taken) + len(clauses[ci]) / 2 <= target - sum(len(x) for y in ko_chunks for x in [y])):
                taken.append(clauses[ci])
                ci += 1
            if not taken and ci < len(clauses):
                taken.append(clauses[ci])
                ci += 1
            ko_chunks.append(" ".join(taken))
    assert all(ko_chunks), f"한국어 분할 실패: {ln.ko}"
    out = []
    for k, (ja, ko) in enumerate(zip(ja_chunks, ko_chunks)):
        out.append(L(ln.style, ja, ko, ln.emotion, ln.speed, ln.gap if k == 0 else 0.0,
                     ln.direction if k == 0 else "(앞 줄 이어서)"))
    return out


