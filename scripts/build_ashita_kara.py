def cut(n, who, scene, move, speed, framing, end, sound, dialogue=None):
    """규칙집 5블록 컷 프롬프트 ([DURATION]은 배분 뒤 삽입)."""
    if n:
        lock = f"[LOCK] 프레임 안의 인물은 정확히 {n}명: {who}. {FILM}"
    else:
        lock = f"[LOCK] 사람이 한 명도 없는 무인 장면, 인물 없음. {FILM}"
    dlg = (f"[DIALOGUE] {dialogue} — 정면 상반신, 일본어로 말하는 입 모양을 자연스럽게 움직임, "
           f"영어 없음" if dialogue else "[DIALOGUE] none")
    return (f"{lock} [SCENE] {scene} [CAMERA] Movement: {move}; Speed: {speed}; "
            f"Framing: {framing}; End: {end} {dlg} [SOUND] {sound}")


