CHAR_RATE = 5.0   # 일본어 낭독 초당 글자 수(공백·구두점 제외)
LINE_PAD = 0.5
MIN_DUR = 1.2


def line_duration(text):
    chars = len(re.sub(r"[\s、。！？!?…「」『』（）()・―]", "", text))
    return max(MIN_DUR, chars / CHAR_RATE + LINE_PAD)


def fmt_time(t):
    t = max(t, 0.0)
    return f"{int(t // 3600)}:{int(t % 3600 // 60):02d}:{t % 60:05.2f}"


def fmt_srt(t):
    t = max(t, 0.0)
    ms = int(round((t - int(t)) * 1000))
    return f"{int(t // 3600):02d}:{int(t % 3600 // 60):02d}:{int(t % 60):02d},{ms:03d}"


