def load():
    t = open(os.path.join(HERE, "00_script_ja.md"), encoding="utf-8").read()
    body = t.split("## 4. 대본")[1].split("## 5.")[0]
    out = []
    for m in re.finditer(r"^\s+((?:NA|L)\d+[a-z]?)\s*([^\s:「(\[]*)[^「\n]*「(.+)」", body, re.M):
        tag, spk, text = m.group(1), m.group(2), m.group(3)
        out.append((tag, "NA" if tag.startswith("NA") else spk, text))
    for m in re.finditer(r"^(OUT3)\b[^\n]*\n\s*「(.+)」", body, re.M):
        out.append((m.group(1), "OUT", m.group(2)))
    return out


def sentences(text):
    parts = re.split(r"(?<=[。！？])\s*", text.replace("――", "。"))
    return [p for p in (x.strip(" 　") for x in parts) if re.sub(r"[……、。！？\s　]", "", p)]


def check_lengths(lines):
    bad = []
    for tag, _, text in lines:
        ss = sentences(text)
        if len(ss) > 2:
            bad.append(f"{tag}: {len(ss)}문장")
        for s in ss:
            n = len(re.sub(r"[、。！？…\s　\"『』]", "", s))
            if n > 30:
                bad.append(f"{tag}: {n}자 「{s}」")
    return bad


