def kana_tag(tag, s):
    for a, b in TAG_KANA.get(tag, []):
        s = s.replace(a, b)
    for a, b in KANA:
        s = s.replace(a, b)
    return s


def load():
    t = open(os.path.join(HERE, "00_script_ja.md"), encoding="utf-8").read()
    body = t.split("## 4. 대본")[1].split("## 5.")[0]
    body = "\n".join(l for l in body.splitlines() if not re.match(r"^\s+OUT[15]\b", l))  # 몽타주·손 흔들기(대사 없음)
    out = []
    for m in re.finditer(r"^\s+((?:NA|L)\d+[a-z]?)\s*([^\s:「(\[]*)[^「\n]*「(.+)」", body, re.M):
        tag, spk, text = m.group(1), m.group(2), m.group(3)
        out.append((tag, "NA" if tag.startswith("NA") else spk, text))
    for m in re.finditer(r"^(OUT3)\b[^\n]*\n\s*「(.+)」", body, re.M):  # 진행자 멘트(OUT3만 신규 녹음, OUT2·OUT4는 재사용)
        out.append((m.group(1), "OUT", m.group(2)))
    return out


